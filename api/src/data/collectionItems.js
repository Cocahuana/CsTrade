/**
 * Get all possible outcome items for a given collection and input rarity
 * @param {string} collectionName - The collection name
 * @param {string} inputRarity - The input rarity tier
 * @returns {string[]} - Array of possible outcome item names
 */
export function getPossibleOutcomes(collectionName, inputRarity) {
	const rarityTiers = [
		"Consumer Grade",
		"Industrial Grade",
		"Mil-Spec Grade",
		"Restricted",
		"Classified",
		"Covert",
	];

	const currentIndex = rarityTiers.findIndex((r) => inputRarity.includes(r));
	if (currentIndex === -1 || currentIndex === rarityTiers.length - 1) {
		return []; // Invalid rarity or already at max
	}

	const nextRarity = rarityTiers[currentIndex + 1];
	const collection = COLLECTION_ITEMS[collectionName];

	if (!collection || !collection[nextRarity]) {
		return [];
	}

	return collection[nextRarity];
}

/**
 * Get all items from a specific collection and rarity
 * @param {string} collectionName - The collection name
 * @param {string} rarity - The rarity tier
 * @returns {string[]} - Array of item names
 */
export function getItemsByCollectionAndRarity(collectionName, rarity) {
	const collection = COLLECTION_ITEMS[collectionName];
	if (!collection || !collection[rarity]) {
		return [];
	}
	return collection[rarity];
}

/**
 * Get all collections that contain a specific item
 * @param {string} itemName - The base item name (e.g., "AK-47 | Redline")
 * @returns {string[]} - Array of collection names
 */
export function getCollectionsForItem(itemName) {
	const collections = [];

	for (const [collectionName, rarities] of Object.entries(COLLECTION_ITEMS)) {
		for (const items of Object.values(rarities)) {
			if (items.some((item) => itemName.includes(item))) {
				collections.push(collectionName);
				break;
			}
		}
	}

	return collections;
}

/**
 * Check if an item exists in a collection
 * @param {string} itemName - The item name
 * @param {string} collectionName - The collection name
 * @returns {boolean}
 */
export function isItemInCollection(itemName, collectionName) {
	const collection = COLLECTION_ITEMS[collectionName];
	if (!collection) return false;

	for (const items of Object.values(collection)) {
		if (items.some((item) => itemName.includes(item))) {
			return true;
		}
	}

	return false;
}

/**
 * Get rarity of an item in a collection
 * @param {string} itemName - The item name
 * @param {string} collectionName - The collection name
 * @returns {string|null} - Rarity tier or null if not found
 */
export function getItemRarity(itemName, collectionName) {
	const collection = COLLECTION_ITEMS[collectionName];
	if (!collection) return null;

	for (const [rarity, items] of Object.entries(collection)) {
		if (items.some((item) => itemName.includes(item))) {
			return rarity;
		}
	}

	return null;
}

